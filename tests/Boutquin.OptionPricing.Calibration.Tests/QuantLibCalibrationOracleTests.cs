    [Theory]
    [MemberData(nameof(Cases))]
    public void SurfaceProviderAndImpliedVolatility_AgreeWithQuantLib(bool put, int strike, double sigma,
        double rate, double dividend, double borrow, int days, double premium)
    {
        var date = new DateOnly(2026, 1, 1);
        var expiry = date.AddDays(days);
        var market = new OptionMarketData(date, Currency.USD.Amount(100m), sigma,
            new FlatDiscountCurve(new CurveName("r"), date, Currency.USD, rate),
            new FlatDiscountCurve(new CurveName("q"), date, Currency.USD, dividend),
            new FlatDiscountCurve(new CurveName("b"), date, Currency.USD, borrow));
        double t = market.TimeToExpiryInYears(expiry);
        var surface = new VolatilitySurface(new[] { new SmileSlice(t, new[] { new SurfacePoint(t, strike, sigma) }) });
        var provider = new SurfaceDerivedPriceProvider(surface, market, expiry);
        (put ? provider.GetPutPrice(strike, expiry) : provider.GetCallPrice(strike, expiry))
            .Should().BeApproximately(premium, 1e-10);
        (put ? provider.GetPutPrice(strike, t) : provider.GetCallPrice(strike, t))
            .Should().BeApproximately(premium, 1e-10);
        var option = new EuropeanOption(put ? CallPut.Put : CallPut.Call, strike, Currency.USD, expiry);
        var solved = new ImpliedVolatilitySolver().Solve(new ImpliedVolatilityRequest(option, market,
            (decimal)premium, 0.25, 1e-10, 1e-10));
        solved.IsSuccess.Should().BeTrue();
        solved.ImpliedVolatility.Should().BeApproximately(sigma, 1e-7);
    }

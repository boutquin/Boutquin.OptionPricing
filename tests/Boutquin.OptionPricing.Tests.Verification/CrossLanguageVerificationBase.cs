using System.Globalization;
using System.Text.Json;
using Boutquin.Curves.Abstractions.Identifiers;
using Boutquin.MarketData.Abstractions.ReferenceData;
using Boutquin.Curves.Core.Discounting;
using Boutquin.OptionPricing.Domain.Contracts;
using Boutquin.OptionPricing.Domain.Enums;
using Boutquin.OptionPricing.Domain.Market;

namespace Boutquin.OptionPricing.Tests.Verification;

/// <summary>
/// Base class for cross-language verification tests. Loads JSON vectors
/// generated by the Python <c>tests/Verification/generate_*.py</c> scripts
/// and provides tiered precision helpers and shared market-data construction.
/// </summary>
public abstract class CrossLanguageVerificationBase
{
    /// <summary>Exact arithmetic — pure algebra, parity identities.</summary>
    protected const double PrecisionExact = 1e-10;

    /// <summary>
    /// Closed-form with normal CDF, or identical-algorithm binomial tree in double
    /// arithmetic. Tolerates floating-point summation-order differences.
    /// </summary>
    protected const double PrecisionNumeric = 1e-6;

    /// <summary>Statistical / convergence bounds for tree → analytic-limit assertions.</summary>
    protected const double PrecisionStatistical = 1e-4;

    private const CurrencyCode UsdCurrency = CurrencyCode.USD;

    private static string? s_vectorsDir;

    /// <summary>
    /// Resolves the JSON vectors directory. Prefers the output-tree copy set up by
    /// the csproj's <c>Content Include</c>, falling back to walking up from the
    /// test assembly to <c>tests/Verification/vectors/</c> for local debugging.
    /// </summary>
    protected static string GetVectorsDir()
    {
        if (s_vectorsDir != null)
        {
            return s_vectorsDir;
        }

        var outputCopy = Path.Combine(AppContext.BaseDirectory, "Verification", "vectors");
        if (Directory.Exists(outputCopy))
        {
            s_vectorsDir = outputCopy;
            return outputCopy;
        }

        var dir = AppContext.BaseDirectory;
        while (dir != null)
        {
            var candidate = Path.Combine(dir, "tests", "Verification", "vectors");
            if (Directory.Exists(candidate))
            {
                s_vectorsDir = candidate;
                return candidate;
            }

            dir = Directory.GetParent(dir)?.FullName;
        }

        throw new DirectoryNotFoundException(
            "Cannot find tests/Verification/vectors/. Run the Python generators first.");
    }

    protected static JsonDocument LoadVector(string name)
    {
        var path = Path.Combine(GetVectorsDir(), $"{name}.json");
        if (!File.Exists(path))
        {
            throw new FileNotFoundException(
                $"Vector file not found: {path}. Run the Python generator first.",
                path);
        }

        var json = File.ReadAllText(path);
        return JsonDocument.Parse(json);
    }

    protected static void AssertWithin(double actual, double expected, double tolerance, string label)
    {
        var diff = Math.Abs(actual - expected);
        Assert.True(diff <= tolerance,
            $"{label}: expected {expected}, got {actual}, diff={diff} > tol={tolerance}");
    }

    /// <summary>
    /// Parses an ISO 8601 date string produced by the Python generator using the
    /// invariant culture so that locale drift can never alter the vectors' dates.
    /// </summary>
    protected static DateOnly ParseDate(string value) =>
        DateOnly.Parse(value, CultureInfo.InvariantCulture);

    protected static CallPut ParseCallPut(string value) => value switch
    {
        "Call" => CallPut.Call,
        "Put" => CallPut.Put,
        _ => throw new ArgumentOutOfRangeException(nameof(value), value, "Unknown call/put flag."),
    };

    /// <summary>
    /// Builds an <see cref="OptionMarketData"/> snapshot from the flat continuously
    /// compounded rates supplied in a verification scenario. When a rate is zero,
    /// the corresponding curve is still constructed (yielding DF = 1.0) to keep
    /// the curve-type diagnostic metadata consistent across scenarios.
    /// </summary>
    protected static OptionMarketData BuildMarket(
        DateOnly valuationDate,
        decimal spot,
        double sigma,
        double r,
        double q,
        double b = 0d)
    {
        var discount = new FlatDiscountCurve(
            new CurveName("USD-OIS"), valuationDate, UsdCurrency, r);
        var dividend = new FlatDiscountCurve(
            new CurveName("DIVIDEND"), valuationDate, UsdCurrency, q);
        FlatDiscountCurve? borrow = null;
        if (b != 0d)
        {
            borrow = new FlatDiscountCurve(
                new CurveName("BORROW"), valuationDate, UsdCurrency, b);
        }

        return new OptionMarketData(
            valuationDate,
            spot,
            sigma,
            discount,
            dividend,
            borrow);
    }

    protected static EuropeanOption BuildEuropeanOption(decimal strike, DateOnly expiry, string callPut) =>
        new(ParseCallPut(callPut), strike, expiry);

    protected static AmericanOption BuildAmericanOption(decimal strike, DateOnly expiry, string callPut) =>
        new(ParseCallPut(callPut), strike, expiry);
}
